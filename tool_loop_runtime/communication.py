"""Host-bound tool execution, coordinate references and communication metadata."""
from __future__ import annotations

from collections import defaultdict
import json
from pathlib import Path
import re
import time

from table_tools import TableTools, ProgramError
from . import transport

REFERENCE = re.compile(r"\{\{coord:([A-Za-z][A-Za-z0-9_]{0,63})\}\}")


class ToolStageFailure(ValueError):
    def __init__(self, error, return_to=None):
        self.error, self.return_to = error, return_to
        super().__init__(error["message"])


def digest_value(value):
    return transport.digest(json.dumps(value, ensure_ascii=False, sort_keys=True).encode())


class ToolSession:
    def __init__(self, row, understanding, sample_dir, prefix):
        self.sample_dir, self.prefix = Path(sample_dir), prefix
        self.service = None
        then = time.monotonic()
        try:
            self.service = TableTools(row["id"], understanding, state_dir=self.sample_dir/"tools")
        except ProgramError as exc:
            self.event("host", "register_tables", {"sample_id": row["id"]}, {"ok": False, "error": exc.record()}, then)
            target = "understand" if exc.recovery == "revise_understanding" else None
            raise ToolStageFailure(exc.record(), target) from exc
        self.event("host", "register_tables", {"sample_id": row["id"]},
                   {"ok": True, "context_id": self.service.context_id, "table_version": self.service.table_version}, then)

    def event(self, role, name, args, response, started):
        record = {"time": transport.stamp(), "round": self.prefix, "role": role, "tool": name,
                  "arguments": args, "response": response, "seconds": round(time.monotonic()-started, 6)}
        with (self.sample_dir/"tool_events.jsonl").open("a", encoding="utf-8") as file:
            file.write(json.dumps(record, ensure_ascii=False)+"\n")

    def call(self, role, name, arguments, stage, *, target=None, required=True):
        # Identity is supplied by the host's current session, never generated by an agent.
        args = {"table_version": self.service.table_version, **arguments}
        then = time.monotonic()
        response = self.service.call(role, name, args)
        self.event(role, name, args, response, then)
        transport.save_json(self.sample_dir/(stage+".json"), {"role": "program", "tool": name, "input": args, "output": response})
        if required and not response["ok"]:
            recovery = response["error"].get("recovery")
            if recovery in ("fix_host_storage", "restore_matching_context"):
                target = None
            raise ToolStageFailure(response["error"], target)
        return response

    def catalog(self):
        return self.call("select", "list_tables", {}, self.prefix+"00t_index")["data"]

    def extract(self, selection, indexed):
        regions = selection["regions"]
        fallback = regions == []
        if fallback:
            # No region is not a semantic absence judgment. Let the solver see
            # all recognized tables without spending the content rework quota.
            if indexed["table_version"] != self.service.table_version:
                raise ToolStageFailure({"code": "STALE_HOST_INDEX", "message": "Full-table fallback requires the current index"})
            regions = [{"id": f"full_{number}", "source_table_id": table["id"],
                        "rows": [1, table["row_count"]], "columns": [1, table["column_count"]]}
                       for number, table in enumerate(indexed["tables"], 1)]
        resolution = {"mode": "full_table_after_empty_selection" if fallback else "selected_regions",
                      "requested_regions": selection["regions"], "effective_requests": regions}
        transport.save_json(self.sample_dir/(self.prefix+"selection_resolution.json"), resolution)
        response = self.call("select", "extract_subtables", {"regions": regions},
                             self.prefix+"03t_extract", target="select")
        data = response["data"]
        data = dict(data, selection_resolution=resolution)
        transport.save_json(self.sample_dir/(self.prefix+"03_extract.json"), {"role": "program", **data})
        return data


def route_checker(judgment):
    """Route only from agent-assigned stage tags, never interpret its prose."""
    issues = judgment["issues"]
    stages = [issue["source_stage"] for issue in issues]
    priority = ("understand", "select", "solve")
    target = "none"
    if judgment["status"] != "passed" and "unknown" not in stages:
        target = next((stage for stage in priority if stage in stages), "none")
    return dict(judgment, return_to=target)


def wire_subtables(extraction):
    fields = ("id", "source_table_id", "table_version", "source_rows", "source_columns", "html")
    return [{key: table[key] for key in fields} for table in extraction["subtables"]]


def resolve_answer(solver, session, extraction):
    """Replace named coordinate references only. Never inspect or rewrite other numbers."""
    requests = solver.get("coordinate_requests", [])
    by_id = {}
    for request in requests:
        if request["id"] in by_id:
            raise ToolStageFailure({"code": "DUPLICATE_COORDINATE_ID", "message": "Coordinate request IDs must be unique"}, "solve")
        by_id[request["id"]] = request
    tokens = REFERENCE.findall(solver["answer"])
    if set(tokens) != set(by_id):
        raise ToolStageFailure({"code": "COORDINATE_REFERENCE_MISMATCH", "message": "Each named coordinate reference must match a request, with no unused requests"}, "solve")
    if "{{coord:" in REFERENCE.sub("", solver["answer"]):
        raise ToolStageFailure({"code": "INVALID_COORDINATE_REFERENCE", "message": "Malformed {{coord:ID}} reference"}, "solve")
    groups = defaultdict(list)
    for request in requests:
        groups[request["subtable_id"], request["output_base"]].append(request)
    resolved, receipts = {}, []
    counter = 0
    for (subtable_id, base), members in groups.items():
        positions = list(dict.fromkeys(tuple(r["position"]) for r in members))
        mapped = {}
        for start in range(0, len(positions), 64):
            counter += 1
            response = session.call("solve", "map_coordinates", {"extraction_id": extraction["extraction_id"],
                "subtable_id": subtable_id, "direction": "to_source", "positions": [list(p) for p in positions[start:start+64]],
                "output_base": base}, session.prefix+f"04t_map_{counter:02d}", target="solve")
            receipts.append(response)
            for item in response["data"]["positions"]:
                mapped[tuple(item["input"]["position"])] = item["mapped"]
        for request in members:
            result = mapped[tuple(request["position"])]
            component = request["component"]
            if component == "position": value = result["position"]
            elif component == "top_left": value = result["cell_anchor"]
            elif component == "bottom_right": value = [result["cell_rows"][1], result["cell_columns"][1]]
            elif component == "row": value = result["position"][0]
            elif component == "column": value = result["position"][1]
            elif component == "rowspan": value = result["cell_rows"][1]-result["cell_rows"][0]+1
            else: value = result["cell_columns"][1]-result["cell_columns"][0]+1
            text = ("("+", ".join(str(v) for v in value)+")") if type(value) is list and request["format"] == "tuple" else json.dumps(value)
            resolved[request["id"]] = {"value": value, "text": text}
    candidate = {key: solver[key] for key in ("status", "answer", "review_request")}
    candidate["answer"] = REFERENCE.sub(lambda match: resolved[match[1]]["text"], candidate["answer"])
    record = {"role": "program", "answer_template": solver["answer"], "resolved_references": resolved,
              "mapping_results": receipts, "candidate": candidate}
    transport.save_json(session.sample_dir/(session.prefix+"04_coordinates.json"), record)
    return candidate, record


def call_counts(folder):
    models = len(list((Path(folder)/"attempts").glob("*.json")))
    path = Path(folder)/"tool_events.jsonl"
    tools = sum(1 for line in path.read_text(encoding="utf-8").splitlines() if line) if path.exists() else 0
    return {"model_calls": models, "tool_calls": tools}
